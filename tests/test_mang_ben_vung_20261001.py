class _PhanHoi:
    def __init__(self, status_code: int, text: str = "", headers: Any = None, url: str = URL) -> None:
        self.status_code, self.text, self.url = status_code, text, url
        self.headers = {} if headers is None else headers
        self.content = text.encode()

    def raise_for_status(self) -> None:
        if self.status_code >= 400:
            raise requests.HTTPError(f"{self.status_code} Client Error: Forbidden for url: {self.url}")

    def json(self) -> Any:
        return json.loads(self.text)


class _PhienGia:
    """Mỗi lần gọi trả phần tử kế tiếp của `chuoi` (phần tử cuối lặp lại); ngoại lệ thì ném."""

    def __init__(self, *chuoi: Any) -> None:
        self.chuoi, self.so_lan = list(chuoi), 0

    def request(self, method, url, params=None, timeout=None, **extra):
        muc = self.chuoi[min(self.so_lan, len(self.chuoi) - 1)]
        self.so_lan += 1
        if isinstance(muc, BaseException):
            raise muc
        return muc


