def _client(*chuoi: Any) -> HttpClient:
    client = HttpClient(cache_ttl=0, min_interval=0)
    client.session = _PhienGia(*chuoi)
    return client


def _loi_cuoi(client: HttpClient, ngoai_le=Exception, url: str = URL, params: Optional[dict] = None) -> str:
    with pytest.raises(ngoai_le):
        client.get_text(url, params=params)
    return client.last_error


